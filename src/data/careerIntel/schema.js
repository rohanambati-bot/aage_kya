/**
 * ============================================================
 * AI Career Intelligence Hub — Knowledge Base Schema
 * ============================================================
 * This is a NEW, isolated data layer. It does not modify, import from,
 * or get imported by the existing recommendation engine, RAG pipeline,
 * multi-agent system, or database. Every field below is a structured,
 * hand-curated (non-hallucinated) estimate meant for exploratory career
 * analytics — the same "verified knowledge base" pattern already used
 * by src/data/collegeEnrichment.js and src/data/courseReality.js.
 *
 * Every score is 0-100 unless noted otherwise. Every score field carries
 * a paired `reason` string so the UI can render Explainable AI (XAI)
 * tooltips instead of an opaque number — nothing here is generated by
 * an LLM at request time; it's all pre-computed and auditable.
 *
 * Shape of one career record (documented for contributors):
 *
 * {
 *   id, name, category, subCategory, emoji, tags: string[],
 *   streams: string[],                 // e.g. ['Science (PCM)', 'Any Stream']
 *   overview: string,
 *   educationPath: { stage, detail }[],
 *   eligibility: string,
 *   entranceExams: string[],
 *   requiredSkills: string[],
 *   certifications: string[],
 *   salary: { entry, mid, senior,           // INR per annum
 *             entryGlobal, midGlobal, seniorGlobal }, // USD per annum
 *   salaryTimeline: { year, indiaLPA, globalUSD }[],  // years of experience
 *   demand: { current, year5, year10, reason },
 *   jobStability: { score, reason },
 *   industryGrowth: { percent, reason },
 *   globalOpportunities: { score, countries: string[], reason },
 *   workLifeBalance: { score, reason },
 *   aiRisk: { score, reason },              // higher score = higher automation risk
 *   competitionLevel: { score, reason },
 *   learningDifficulty: { score, reason },
 *   roi: { score, reason },
 *   higherEducationOptions: string[],
 *   governmentOpportunities: string[],
 *   entrepreneurshipScope: { score, reason },
 *   topRecruiters: string[],
 *   topColleges: string[],
 *   scholarships: string[],
 *   youtubeResources: { title, channel }[],
 *   roadmap: { phase, detail }[],
 *   relatedCareers: string[],           // ids
 *   advantages: string[],
 *   challenges: string[],
 *   govtCareer: boolean,
 *   studyAbroadFriendly: boolean,
 * }
 * ============================================================
 */

